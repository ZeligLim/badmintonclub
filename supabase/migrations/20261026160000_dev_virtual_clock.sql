-- Dev-only virtual clock. Promote this to production only after review.
create table if not exists public.dev_virtual_clock (
  id integer primary key,
  virtual_now timestamptz null,
  updated_at timestamptz not null default pg_catalog.now()
);

insert into public.dev_virtual_clock (id, virtual_now)
values (1, null)
on conflict (id) do nothing;

revoke all on table public.dev_virtual_clock from public, anon, authenticated;
grant select, update on table public.dev_virtual_clock to anon, authenticated, service_role, supabase_auth_admin;

alter table public.dev_virtual_clock disable row level security;

create or replace function public.get_virtual_now()
returns timestamptz
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select coalesce(virtual_now, pg_catalog.now())
  from public.dev_virtual_clock
  where id = 1;
$$;

revoke all on function public.get_virtual_now() from public, anon, authenticated;
grant execute on function public.get_virtual_now() to anon, authenticated, service_role, supabase_auth_admin;

create or replace function public.set_virtual_now(p_virtual_now timestamptz)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  update public.dev_virtual_clock
  set virtual_now = p_virtual_now,
      updated_at = pg_catalog.now()
  where id = 1;
end;
$$;

revoke all on function public.set_virtual_now(timestamptz) from public, anon, authenticated;
grant execute on function public.set_virtual_now(timestamptz) to anon, authenticated, service_role, supabase_auth_admin;

create or replace function public.reset_virtual_now()
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  update public.dev_virtual_clock
  set virtual_now = null,
      updated_at = pg_catalog.now()
  where id = 1;
end;
$$;

revoke all on function public.reset_virtual_now() from public, anon, authenticated;
grant execute on function public.reset_virtual_now() to anon, authenticated, service_role, supabase_auth_admin;

-- Override unqualified now() for rebuilt schemas/search paths.
create or replace function public.now()
returns timestamptz
language sql
stable
as $$
  select coalesce(
    (select virtual_now from public.dev_virtual_clock where id = 1),
    pg_catalog.now()
  );
$$;

-- Make the virtual clock visible to built-in and session defaults where possible.
alter database postgres set search_path = public, pg_catalog;
alter role anon set search_path = public, pg_catalog;
alter role authenticated set search_path = public, pg_catalog;
alter role service_role set search_path = public, pg_catalog;

-- Prefer public.now() inside existing routines. pg_proc function signature
-- arguments are regenerated by pg_get_function_identity_arguments.
do $$
declare
  r record;
begin
  for r in
    select n.nspname, p.proname, pg_get_function_identity_arguments(p.oid) as identity_args
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname in ('public', 'private')
      and p.proname <> 'now'
  loop
    execute format(
      'alter function %I.%I(%s) set search_path = public, pg_catalog',
      r.nspname,
      r.proname,
      r.identity_args
    );
  end loop;
end;
$$;
